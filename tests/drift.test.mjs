import assert from 'node:assert/strict';
import { Wire } from '../js/wire.js';
import { DriftView } from '../js/drift-view.js';

globalThis.document = { createElement: () => ({}) };
globalThis.devicePixelRatio = 2;
const motion = { matches: false };
globalThis.matchMedia = () => motion;
Wire.prototype.load = async () => {};
Wire.prototype.draw = () => {};
const canvas = { dataset: {}, getBoundingClientRect: () => ({width: 300, height: 260}) };
const view = new DriftView(canvas);
const sensors = {motionLive:true, gpsLive:false, imu:{yaw:40}, beta:25};
let speed = 35;
const store = {get: () => speed};
view.update(sensors, store, 0);
view.update(sensors, store, 50);
assert.ok(view.angle > 0 && view.angle < 25);
assert.equal(canvas.width, 600);
assert.equal(canvas.height, 520);
motion.matches = true;
sensors.imu.yaw = -40;
view.update(sensors, store, 100);
assert.equal(view.angle, -25);
assert.equal(view.wire.speed, 0);
sensors.motionLive = false;
view.update(sensors, store, 150);
assert.equal(view.angle, 0);
assert.equal(canvas.dataset.live, 'false');
sensors.motionLive = true;
speed = null;
view.update(sensors, store, 200);
assert.equal(canvas.dataset.live, 'false');
sensors.gpsLive = true; sensors.gps = {mph:30};
view.update(sensors, store, 250);
assert.equal(canvas.dataset.live, 'true');
sensors.gps.mph = 0;
view.update(sensors, store, 300);
assert.equal(view.angle, 0);
view.pause();
assert.equal(view.last, null);
console.log('Drift direction, missing inputs, GPS fallback, parked state, resize and reduced motion passed');
